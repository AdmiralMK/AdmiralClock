// ─────────────────────────────────────────────
// РЕЦЕПТЫ UNICODE-ДИАПАЗОНОВ
// ─────────────────────────────────────────────
//
// 0x0020-0x007F, 0x0400-0x04FF
//   Basic Latin (ASCII, 32..127) + весь блок «Кириллица» (русский + украинский и др.).
//   Самый универсальный диапазон: латиница, цифры, знаки препинания, кириллица.
//
// 0x0020, 0x0041-0x005A, 0x0061-0x007A
//   Только английские буквы + пробел, без цифр и без спецсимволов.
//
// 0x0020, 0x0041-0x005A, 0x0060, 0x0061-0x007A
//   То же, что выше, но с обратным апострофом ` (0x0060), нужным для "Olya`Clock".
//
// 0x0020
//   Только пробел. Изолированно бесполезен — как правило, идёт в паре с другими диапазонами.
//
// 0x0041-0x005A
//   Только заглавные латинские буквы A–Z. Пробела нет.
//
// 0x0061-0x007A
//   Только строчные латинские буквы a–z. Пробела нет.
//
// 0x0020, 0x0030-0x0039
//   Только цифры 0–9 и пробел. Идеально для даты, курсов, времени.
//
// Текстовые (для надписей, статусов, заголовков)
// ─────────────────────────────────────────────
// 0x0020-0x007E
//   Весь печатный ASCII (32..126). Без DEL и управляющих символов.
//   Чуть компактнее, чем 0x0020-0x007F, потому что исключает невидимый DEL (127).
//
// 0x0020, 0x0400-0x045F
//   Только русские буквы (А-я, Ё-ё) + пробел. Без латиницы, цифр и пунктуации.
//   Экономия ~70% размера шрифта, если в тексте только кириллица.
//
// 0x0020-0x007E, 0x0400-0x045F
//   Печатный ASCII + русские буквы. Компактнее, чем 0x0020-0x007F, 0x0400-0x04FF
//   (нет «хвоста» украинских/сербских букв и невидимых DEL/C1-контролей).
//
// 0x0020-0x007E, 0x0400-0x045F, 0x2116, 0x20BD
//   То же + знак «№» (0x2116) + знак рубля «₽» (0x20BD).
//   Полезно, если в текстах встречается нумерация или цены.
//
// Специальные (для конкретных строк OlyaClock)
// ─────────────────────────────────────────────
// 0x0020, 0x002B, 0x002D, 0x0030-0x0039, 0x0043, 0x00B0
//   Температура: пробел, +, -, цифры 0-9, C (латинская), ° (знак градуса).
//
// 0x0020, 0x0024, 0x002E, 0x0030-0x0039, 0x20AC
//   Курсы валют: пробел, $, . (точка), цифры 0-9, € (евро 0x20AC).
//
// 0x0020, 0x0030-0x0039, 0x003A, 0x0412, 0x0432, 0x0437, 0x0434, 0x0441, 0x0445
//   Восход/закат: пробел, цифры, :, и только нужные буквы В в з д с х.
//   ⚠️ Работает только для минимального набора. Обычно проще взять весь ASCII + 0x0400-0x045F.
//
// 0x0020, 0x002C, 0x002D, 0x0030-0x0039, 0x0400-0x045F
//   Дата: пробел, запятая, дефис, цифры, вся кириллица.
//
// Ультракомпактные (для цифровых дисплеев)
// ─────────────────────────────────────────────
// 0x0030-0x0039
//   Только цифры. Даже без пробела. Для полей, где нужны чисто числа.
//
// 0x0020, 0x002B, 0x002D, 0x0030-0x0039
//   пробел, +, -, цифры. Для температур и любых «знаковых» чисел.
//
// 0x0020, 0x002B, 0x002D, 0x0030-0x0039, 0x003A, 0x002E, 0x00B0
//   + двоеточие, точка, градус. Универсальный «цифровой» шрифт для часов,
//   температур и времени суток одновременно.
//
// 0x0041-0x005A, 0x0061-0x007A
//   Только латинские буквы без пробела. Годится для заголовков вроде "Admiral".
//
// 0x0030-0x0039, 0x0041-0x005A
//   Цифры + заглавные A-Z. Для ретро-стиля «12H AM/PM» или шкал.
//
// Прочие полезные
// ─────────────────────────────────────────────
// 0x0020-0x00FF
//   Basic Latin + Latin-1 Supplement. Включает западноевропейские буквы
//   (é, ñ, ü, ß), знаки валют (£, ¥, ¢) и ° (0x00B0).
//
// 0x0020-0x007E, 0x0400-0x04FF, 0x2116, 0x20BD, 0x20AC
//   «Полный набор OlyaClock»: ASCII + вся кириллица + № + ₽ + €.
//   Всё, что может когда-либо встретиться в текущем проекте.

